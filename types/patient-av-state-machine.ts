/**
 * Patient A/V State Machine Type Definitions
 *
 * Defines the event-driven architecture for synchronizing real-time voice
 * interaction (native_audio_function_call_sandbox) with dynamic video loops
 * (veo_cameos) in Module 1: The Living Patient Encounter.
 *
 * @module patient-av-state-machine
 */

// ============================================================================
// CLINICAL TRIGGERS
// ============================================================================

/**
 * Clinical trigger categories that drive state transitions.
 * These are derived from PatientEncounterSession.physicalFindings and vitals.
 */
export type ClinicalTriggerType =
  | 'respiratory' // O2 sat, respiratory rate, breath sounds
  | 'cardiovascular' // HR, BP, cardiac findings
  | 'neurological' // Mental status, GCS, focal deficits
  | 'pain' // Pain scale, location, character
  | 'metabolic' // Temperature, glucose, consciousness
  | 'trauma' // Physical injury, bleeding
  | 'psychological' // Anxiety, agitation, confusion
  | 'environmental'; // Room, setting, time-of-day

/**
 * Clinical severity levels that modulate AV presentation.
 */
export type ClinicalSeverity = 'stable' | 'mild' | 'moderate' | 'severe' | 'critical';

/**
 * A clinical trigger that can cause a state transition.
 */
export interface ClinicalTrigger {
  /** Unique trigger identifier (e.g., "hypoxia_severe", "pain_chest") */
  id: string;

  /** Trigger category */
  type: ClinicalTriggerType;

  /** Severity level */
  severity: ClinicalSeverity;

  /** Human-readable description */
  description: string;

  /** Condition expression evaluated against vitals/physicalFindings JSON */
  condition: ClinicalConditionExpression;

  /** Priority (1-10, higher = more urgent) for competing triggers */
  priority: number;

  /** Timestamp when trigger was activated (ISO 8601) */
  activatedAt?: string;
}

/**
 * Expression tree for evaluating clinical conditions.
 * Examples:
 * - { field: "vitals.o2", operator: "lt", value: 88 }
 * - { operator: "and", conditions: [...] }
 */
export type ClinicalConditionExpression =
  | {
      field: string; // JSON path (e.g., "vitals.o2", "physicalFindings.lungSounds")
      operator: 'eq' | 'neq' | 'lt' | 'lte' | 'gt' | 'gte' | 'contains' | 'in';
      value: string | number | boolean | string[];
    }
  | {
      operator: 'and' | 'or' | 'not';
      conditions: ClinicalConditionExpression[];
    };

// ============================================================================
// AUDIO-VISUAL STATES
// ============================================================================

/**
 * Voice modulation settings for Gemini native_audio_function_call_sandbox.
 */
export interface VoiceModulation {
  /** Voice library ID from Gemini (e.g., "Kore", "Puck", "Aoede") */
  voiceId: string;

  /** Speech rate multiplier (0.5 - 2.0) */
  rate: number;

  /** Pitch shift in semitones (-12 to +12) */
  pitch: number;

  /** Volume multiplier (0.0 - 1.0) */
  volume: number;

  /** Tone descriptors for AI prompt (e.g., "breathless", "agitated", "weak") */
  toneDescriptors: string[];

  /** Whether to apply vocal strain/distortion effects */
  applyVocalStrain: boolean;

  /** Background sounds (e.g., "wheezing", "coughing", "monitor_beeps") */
  backgroundSounds?: string[];
}

/**
 * Video state for veo_cameos integration.
 */
export interface VideoState {
  /** Video loop ID (matches veo_cameos generation) */
  videoId: string;

  /** Video prompt used for generation */
  prompt: string;

  /** Physical presentation (e.g., "Levine sign", "tripod position", "writhing") */
  physicalPresentation: string;

  /** Environment/setting (e.g., "ED", "clinic", "home") */
  environment: 'emergency_department' | 'clinic' | 'home' | 'ambulance';

  /** Loop duration in seconds (typically 3-7s for seamless loops) */
  duration: number;

  /** Transition type when entering this state */
  transitionType: 'immediate' | 'crossfade' | 'medical_scan';

  /** Transition duration in ms */
  transitionDuration: number;

  /** Video URL (once generated by veo_cameos) */
  videoUrl?: string;

  /** Generation status */
  status: 'pending' | 'generating' | 'ready' | 'error';
}

/**
 * Combined audio-visual state definition.
 */
export interface AVState {
  /** Unique state identifier (e.g., "stable_baseline", "hypoxia_severe") */
  id: string;

  /** Human-readable state name */
  name: string;

  /** Clinical context for this state */
  clinicalContext: string;

  /** Voice modulation settings */
  voice: VoiceModulation;

  /** Video presentation */
  video: VideoState;

  /** System prompt override for AI patient in this state */
  systemPromptOverride?: string;

  /** Auto-transition rules (if any) */
  autoTransitions?: StateTransitionRule[];
}

// ============================================================================
// STATE MACHINE DEFINITION
// ============================================================================

/**
 * Transition rule that defines when and how to move between states.
 */
export interface StateTransitionRule {
  /** Target state ID */
  toState: string;

  /** Clinical triggers that activate this transition */
  triggers: ClinicalTrigger[];

  /** Cooldown in seconds before this transition can fire again */
  cooldown?: number;

  /** Whether this transition is reversible (can auto-revert) */
  reversible: boolean;

  /** Reversion condition (if reversible) */
  reversionCondition?: ClinicalConditionExpression;

  /** Optional student action requirement (e.g., "administer_oxygen") */
  requiresStudentAction?: string;
}

/**
 * Complete state machine definition for a patient encounter.
 */
export interface PatientAVStateMachine {
  /** Unique machine ID (typically matches caseId) */
  id: string;

  /** Version for schema evolution */
  version: string;

  /** Initial state ID */
  initialState: string;

  /** All possible states */
  states: Record<string, AVState>;

  /** Global transition rules (apply from any state) */
  globalTransitions: StateTransitionRule[];

  /** State-specific transitions */
  stateTransitions: Record<string, StateTransitionRule[]>;

  /** Metadata */
  metadata: {
    caseId: string;
    patientName: string;
    chiefComplaint: string;
    createdAt: string;
    updatedAt: string;
  };
}

// ============================================================================
// RUNTIME STATE & EVENTS
// ============================================================================

/**
 * Current runtime state of the A/V engine.
 */
export interface AVEngineState {
  /** Current state ID */
  currentState: string;

  /** State history (state ID + timestamp) */
  stateHistory: Array<{ stateId: string; timestamp: string; trigger?: string }>;

  /** Active clinical triggers */
  activeTriggers: ClinicalTrigger[];

  /** Current vitals snapshot */
  currentVitals: {
    hr: number;
    bp: string;
    temp: number;
    rr: number;
    o2: number;
    [key: string]: string | number;
  };

  /** Current physical findings snapshot */
  currentPhysicalFindings: Record<string, unknown>;

  /** Student actions performed (for transition requirements) */
  studentActions: Array<{ action: string; timestamp: string }>;

  /** Last transition timestamp */
  lastTransitionAt: string;
}

/**
 * Event types for the A/V state machine.
 */
export type AVEventType =
  | 'STATE_ENTER'
  | 'STATE_EXIT'
  | 'TRIGGER_ACTIVATED'
  | 'TRIGGER_DEACTIVATED'
  | 'TRANSITION_REQUESTED'
  | 'TRANSITION_COMPLETED'
  | 'TRANSITION_FAILED'
  | 'VITALS_UPDATED'
  | 'PHYSICAL_FINDINGS_UPDATED'
  | 'STUDENT_ACTION'
  | 'VIDEO_GENERATED'
  | 'VIDEO_ERROR'
  | 'VOICE_MODULATION_UPDATED';

/**
 * Base event structure.
 */
export interface AVEvent {
  type: AVEventType;
  timestamp: string;
  sessionId: string;
  payload: unknown;
}

/**
 * State transition event.
 */
export interface StateTransitionEvent extends AVEvent {
  type: 'TRANSITION_COMPLETED';
  payload: {
    fromState: string;
    toState: string;
    trigger?: ClinicalTrigger;
    duration: number;
  };
}

/**
 * Trigger activation event.
 */
export interface TriggerActivationEvent extends AVEvent {
  type: 'TRIGGER_ACTIVATED';
  payload: {
    trigger: ClinicalTrigger;
    vitalsSnapshot: Record<string, unknown>;
  };
}

/**
 * Vitals update event.
 */
export interface VitalsUpdateEvent extends AVEvent {
  type: 'VITALS_UPDATED';
  payload: {
    vitals: Record<string, string | number>;
    changedFields: string[];
    triggersEvaluated: ClinicalTrigger[];
  };
}

