// WEBSOCKET PROTOCOL
// ============================================================================

/**
 * WebSocket message types for A/V synchronization.
 */
export type AVWebSocketMessageType =
  | 'av_state_sync' // Server → Client: Full state sync
  | 'av_state_transition' // Server → Client: State changed
  | 'av_trigger_activated' // Server → Client: Trigger activated
  | 'av_vitals_update' // Client → Server: Vitals changed
  | 'av_student_action' // Client → Server: Student performed action
  | 'av_video_ready' // Server → Client: Video URL available
  | 'audio' // Bidirectional: Audio chunks (existing)
  | 'transcript' // Server → Client: Transcript segment (existing)
  | 'barge_in' // Client → Server: Interrupt (existing)
  | 'tts_start' // Server → Client: AI started speaking (existing)
  | 'tts_end'; // Server → Client: AI stopped speaking (existing)

/**
 * WebSocket message structure.
 */
export interface AVWebSocketMessage {
  type: AVWebSocketMessageType;
  timestamp: string;
  payload: unknown;
}

/**
 * State sync message (server → client).
 */
export interface AVStateSyncMessage extends AVWebSocketMessage {
  type: 'av_state_sync';
  payload: {
    currentState: AVState;
    engineState: AVEngineState;
    availableActions: string[];
  };
}

/**
 * State transition message (server → client).
 */
export interface AVStateTransitionMessage extends AVWebSocketMessage {
  type: 'av_state_transition';
  payload: {
    fromState: string;
    toState: string;
    newStateDefinition: AVState;
    trigger?: ClinicalTrigger;
    transitionAnimation: {
      type: 'immediate' | 'crossfade' | 'medical_scan';
      duration: number;
    };
  };
}

/**
 * Vitals update message (client → server).
 */
export interface AVVitalsUpdateMessage extends AVWebSocketMessage {
  type: 'av_vitals_update';
  payload: {
    vitals: Record<string, string | number>;
    physicalFindings?: Record<string, unknown>;
  };
}

/**
 * Student action message (client → server).
 */
export interface AVStudentActionMessage extends AVWebSocketMessage {
  type: 'av_student_action';
  payload: {
    action: string;
    parameters?: Record<string, unknown>;
  };
}

