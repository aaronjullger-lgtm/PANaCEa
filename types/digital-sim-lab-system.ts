/**
 * Anatomical landmark for procedures.
 */
export interface AnatomicalLandmark {
  /** Landmark ID */
  id: string;

  /** Landmark name */
  name: string;

  /** Description */
  description: string;

  /** Image showing landmark */
  imageUrl: string;

  /** 3D model (if available) */
  modelUrl?: string;

  /** Coordinates on image/model (normalized 0-1) */
  coordinates: { x: number; y: number; z?: number };

  /** Palpation technique */
  palpationTechnique?: string;

  /** Visual identification tips */
  visualTips: string[];

  /** Common errors */
  commonErrors: string[];
}

/**
 * Landmark identification quiz.
 */
export interface LandmarkIdentificationQuiz {
  /** Quiz ID */
  id: string;

  /** Procedure */
  procedureId: string;

  /** Landmarks to identify */
  landmarks: AnatomicalLandmark[];

  /** Base image */
  baseImageUrl: string;

  /** Student clicks */
  studentClicks: Array<{
    landmarkId: string;
    position: { x: number; y: number };
    timestamp: string;
  }>;

  /** Scoring */
  scoring: {
    maxDistanceForCredit: number; // Normalized
    pointsPerLandmark: number;
  };

  /** Feedback */
  feedback?: string;
}

// ============================================================================
// PROCEDURE SIMULATION
