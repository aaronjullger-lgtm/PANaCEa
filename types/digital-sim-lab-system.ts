// PROCEDURAL WORKFLOW
// ============================================================================

/**
 * Clinical procedure categories.
 */
export type ProcedureCategory =
  | 'vascular_access' // IV, Central line, Arterial line
  | 'airway_management' // Intubation, Cricothyrotomy
  | 'chest_procedures' // Chest tube, Needle decompression
  | 'wound_care' // Suturing, Stapling, Dressing
  | 'diagnostic' // Lumbar puncture, Paracentesis, Arthrocentesis
  | 'cardiac' // CPR, Defibrillation, Cardioversion
  | 'orthopedic' // Splinting, Reduction
  | 'emergency'; // Tourniquet, Packing, Emergent procedures

/**
 * Individual procedural step.
 */
export interface ProceduralStep {
  /** Step number */
  stepNumber: number;

  /** Step name */
  name: string;

  /** Description */
  description: string;

  /** Detailed instructions */
  instructions: string;

  /** Visual aids */
  media: {
    /** Step animation URL (generated by bring_any_idea_to_life) */
    animationUrl?: string;

    /** Static image URLs */
    imageUrls?: string[];

    /** Landmark diagram */
    landmarkDiagramUrl?: string;
  };

  /** Critical actions for this step */
  criticalActions: string[];

  /** Common mistakes */
  commonMistakes: string[];

  /** Safety considerations */
  safetyConsiderations: string[];

  /** Time estimate (seconds) */
  timeEstimate: number;

  /** Is this step optional */
  isOptional: boolean;

  /** Dependencies (must complete these steps first) */
  dependencies: number[];
}

/**
 * Complete procedural workflow.
 */
export interface ProceduralWorkflow {
  /** Procedure ID */
  id: string;

  /** Procedure name */
  name: string;

  /** Category */
  category: ProcedureCategory;

  /** Description */
  description: string;

  /** Indications */
  indications: string[];

  /** Contraindications */
  contraindications: string[];

  /** Steps */
  steps: ProceduralStep[];

  /** Required equipment */
  requiredEquipment: EquipmentItem[];

  /** Complications */
  complications: string[];

  /** Total estimated time */
  totalTimeEstimate: number;

  /** Difficulty level */
  difficulty: 'beginner' | 'intermediate' | 'advanced';

  /** PANCE relevance */
  panceRelevance: number;
}

// ============================================================================
// EQUIPMENT & STERILE FIELD
// ============================================================================

/**
 * Equipment item.
 */
export interface EquipmentItem {
  /** Item ID */
  id: string;

  /** Item name */
  name: string;

  /** Category */
  category: 'instrument' | 'supply' | 'medication' | 'protective_equipment';

  /** Image URL */
  imageUrl: string;

  /** 3D model URL (if available) */
  modelUrl?: string;

  /** Is sterile */
  isSterile: boolean;

  /** Quantity required */
  quantity: number;

  /** Description */
  description: string;

  /** Common substitutes */
  substitutes?: string[];
}

/**
 * Sterile field configuration.
 */
export interface SterileField {
  /** Field ID */
  id: string;

  /** Field type */
  type: 'full_drape' | 'partial_drape' | 'no_drape';

  /** Safe zone coordinates (normalized 0-1) */
  safeZone: {
    type: 'rectangle' | 'circle' | 'polygon';
    bounds: Array<{ x: number; y: number }>;
  };

  /** Border zone (transition area) */
  borderZone?: {
    width: number; // Pixels
    warningEnabled: boolean;
  };

  /** Contamination tracking */
  contaminationTracking: {
    /** Is tracking enabled */
    enabled: boolean;

    /** Contamination events */
    events: Array<{
      timestamp: string;
      position: { x: number; y: number };
      severity: 'minor' | 'major';
      recovered: boolean;
    }>;
  };

  /** Visual feedback */
  visualFeedback: {
    /** Highlight safe zone */
    highlightSafeZone: boolean;

    /** Safe zone color */
    safeZoneColor: string;

    /** Contamination indicator color */
    contaminationColor: string;

    /** Glow effect on hover */
    glowEffect: boolean;
  };
}

/**
 * Equipment tray (pre-procedure setup).
 */
export interface EquipmentTray {
  /** Tray ID */
  id: string;

  /** Procedure ID */
  procedureId: string;

  /** Required items */
  requiredItems: EquipmentItem[];

  /** Student-selected items */
  selectedItems: string[]; // Equipment IDs

  /** Missing items */
  missingItems: string[];

  /** Unnecessary items (selected but not needed) */
  unnecessaryItems: string[];

  /** Tray completion status */
  isComplete: boolean;

  /** Penalty for missing items */
  missingItemPenalty: number;

  /** Penalty for unnecessary items */
  unnecessaryItemPenalty: number;
}

// ============================================================================
// SURGICAL GEOMETRY & INSTRUMENT HANDLING
// ============================================================================

/**
 * Instrument grip type.
 */
export type InstrumentGrip =
  | 'pen_grip' // Scalpel, suture holder
  | 'palm_grip' // Retractor
  | 'pinch_grip' // Forceps, pickups
  | 'ring_finger_grip' // Scissors, hemostats
  | 'two_handed'; // Needle driver

/**
 * Instrument handling parameters.
 */
export interface InstrumentHandling {
  /** Instrument ID */
  instrumentId: string;

  /** Correct grip type */
  correctGrip: InstrumentGrip;

  /** Approach angle (degrees from perpendicular) */
  approachAngle: {
    ideal: number;
    acceptable: { min: number; max: number };
  };

  /** Entry depth (for needles/blades) */
  entryDepth?: {
    ideal: number; // mm
    acceptable: { min: number; max: number };
  };

  /** Force range */
  forceRange?: {
    min: number; // Newtons
    max: number;
  };

  /** Movement path */
  movementPath?: {
    type: 'linear' | 'arc' | 'circular' | 'freeform';
    waypoints: Array<{ x: number; y: number; z: number }>;
  };
}

/**
 * Procedural geometry validation.
 */
export interface ProceduralGeometry {
  /** Procedure step ID */
  stepId: string;

  /** Target anatomy */
  targetAnatomy: {
    /** Anatomical structure ID */
    structureId: string;

    /** 3D model URL */
    modelUrl?: string;

    /** Target coordinates */
    targetPoint: { x: number; y: number; z: number };

    /** Safe entry zone */
    safeZone: {
      radius: number; // mm
      avoidanceZones?: Array<{
        name: string; // e.g., "Subclavian artery"
        center: { x: number; y: number; z: number };
        radius: number;
      }>;
    };
  };

  /** Student's approach */
  studentApproach?: {
    entryPoint: { x: number; y: number; z: number };
    angle: number;
    depth: number;
  };

  /** Validation result */
  validation?: {
    isCorrect: boolean;
    distanceFromIdeal: number; // mm
    angleDeviation: number; // degrees
    hitAvoidanceZone: boolean;
    feedback: string;
  };
}

