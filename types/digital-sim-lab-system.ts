/**
 * Procedure simulation session.
 */
export interface ProcedureSimulation {
  /** Session ID */
  id: string;

  /** User ID */
  userId: string;

  /** Workflow */
  workflow: ProceduralWorkflow;

  /** Current step */
  currentStep: number;

  /** Step completion status */
  stepCompletionStatus: Record<
    number,
    {
      completed: boolean;
      timeSpent: number;
      criticalActionsPerformed: string[];
      mistakes: string[];
      score: number;
    }
  >;

  /** Equipment tray */
  equipmentTray: EquipmentTray;

  /** Sterile field */
  sterileField: SterileField;

  /** Geometry validations */
  geometryValidations: ProceduralGeometry[];

  /** Overall score */
  score: {
    preparationScore: number;
    techniqueScore: number;
    safetyScore: number;
    timeScore: number;
    overallScore: number;
  };

  /** Start time */
  startTime: string;

  /** End time */
  endTime?: string;

  /** Status */
  status: 'in_progress' | 'completed' | 'abandoned';
}

/**
 * Procedure simulation feedback.
 */
export interface ProcedureFeedback {
  /** Session ID */
  sessionId: string;

  /** Overall assessment */
  overallAssessment: string;

  /** Strengths */
  strengths: string[];

  /** Areas for improvement */
  areasForImprovement: string[];

  /** Critical errors */
  criticalErrors: string[];

  /** Teaching points */
  teachingPoints: string[];

  /** Next steps */
  nextSteps: string[];

  /** Recommended practice procedures */
  recommendedPractice: string[];
}

// ============================================================================
// ANIMATION GENERATION (BRING_ANY_IDEA_TO_LIFE)
// ============================================================================

/**
 * Animation generation request.
 */
export interface AnimationGenerationRequest {
  /** Procedure step */
  step: ProceduralStep;

  /** Animation style */
  style: 'realistic' | 'schematic' | 'hybrid';

  /** Duration (seconds) */
  duration: number;

  /** View angle */
  viewAngle: 'first_person' | 'third_person' | 'overhead' | 'lateral';

  /** Annotation overlay */
  annotations: {
    enabled: boolean;
    labels?: string[];
    arrows?: boolean;
  };

  /** Speed control */
  speedControl: {
    normalSpeed: number; // 1.0 = real-time
    slowMotionSegments?: Array<{
      startTime: number;
      endTime: number;
      speed: number;
    }>;
  };
}

/**
 * Animation generation response.
 */
export interface AnimationGenerationResponse {
  /** Animation ID */
  id: string;

  /** Video URL */
  videoUrl: string;

  /** Thumbnail URL */
  thumbnailUrl: string;

  /** Duration */
  duration: number;

  /** Generation status */
  status: 'completed' | 'failed';

  /** Error message (if failed) */
  error?: string;
}

